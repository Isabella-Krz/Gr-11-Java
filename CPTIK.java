private static boolean roomOne(String name) {
        // Variable initialization and declaration

        Scanner userInput = new Scanner(System.in); // Reinitialize the scanner since it can't access it from the main

        System.out.printf("\nWelcome to room 1! The computer will pick a random number between 1 and 3. If you guess the number correctly, you will collect rock, but if you guess wrong, you will lose a life! You start with 3 tries.\n", name); // Welcome message

        int userChoice = 0; // Initializes the user's choice
        int compChoice = (int)(Math.random() * 3 + 1); // The computer's random choice is between 1 and 3

        int tries = 3; // The amount of tries the user beginnings with
// Program execution and output

        while (tries > 0) { // Loops until the user looses all their tries (until they loose)

            if (name.equals("cheat")) { // Tells the user what the computer chose if they entered "cheat" as their name
                System.out.printf("The computer chose %d.\n", compChoice);
            }

            System.out.printf("You have %d tries. Please enter a number: ", tries);

            if (userInput.hasNextInt()) {
                userChoice = userInput.nextInt(); // The random number the user chooses. Makes sure the user choice is valid
                if (userChoice >= 1 && userChoice <= 3) { // Make's sure the choice is valid and an int
                    if (userChoice == compChoice) {
                        return true;
                    } else { // If none of the possible choices that let the user gain a point happen, the computer gains a point
                        tries--; // Decrements tries by 1
                        System.out.printf("Sorry, %s, you didn't guess the right number!\n", name);
                    }
                } else {
                    System.out.println("Invalid input. Please enter a number: 1, 2, or 3.\n");
                }
            } else {
                // Input was not an int
                System.out.println("Invalid input. Please enter a number: 1, 2, or 3.\n");
                userInput.next(); // Gets rid of the invalid input token
            }
        }

        if (tries <= 0) {
            System.out.printf("\nSorry, %s, you didn't guess the right number! The computer choose %d.\n\n", name, compChoice);
            return false;
        }

        return false;
    }
   
